use std::{fs, path::Path};

use crate::build::{collect_asset_stems, include_assets_path, to_const_name};

/// Material Icons の長いファイル名からアイコン名だけ取り出す
/// 例: `check_24dp_E3E3E3_FILL0_wght400_GRAD0_opsz24` → `check`
fn icon_stem(file_stem: &str) -> &str {
    ["_24dp", "_32dp"].into_iter().filter_map(|d| {
        file_stem.split_once(d).map(|(head, _)| head)
    }).min_by_key(|d| d.len())
    .unwrap_or(file_stem)
}

/// assets/svg 内の SVG を短い定数名の ImageSource として生成する
pub(crate) fn generate_svg_generated(svg_dir: &Path, out_dir: &String) {
    let svg_files = collect_asset_stems(svg_dir, "svg");

    let mut output = String::from("// @generated by build.rs — do not edit\n\n");
    let mut short_names = Vec::new();

    for file_stem in &svg_files {
        let short = icon_stem(file_stem);
        let const_name = to_const_name(short);
        let asset_path = format!("assets/svg/{file_stem}.svg");
        let uri = format!("bytes://assets/svg/{short}.svg");

        short_names.push(short.to_string());
        output.push_str(&format!("#[allow(dead_code)]\n
pub const {const_name}: egui::ImageSource<'static> = super::bytes_source(\n
\"{uri}\",\n
include_bytes!({}),\n);\n\n",
            include_assets_path(&asset_path),
        ));
    }

    println!("cargo:warning=generated svg: {:?}", short_names);

    let out_path = Path::new(out_dir).join("svg_generated.rs");
    fs::write(&out_path, output).expect("failed to write generated svg");
}
