use std::{fs, path::Path};

use crate::build::{collect_asset_stems, include_assets_path, to_const_name};

/// assets/fonts 内のフォントの一覧を生成
/// * `fonts_dir` - フォントディレクトリのパス
/// * `out_dir` - 出力ディレクトリのパス
pub(crate) fn generate_fonts_generated(fonts_dir: &Path, out_dir: &String) {
    let font_names = collect_asset_stems(fonts_dir, "ttf");
    let mut output = String::from("// @generated by build.rs — do not edit\n\n");

    for font_name in &font_names {
        let const_name = to_const_name(font_name);
        let asset_path = format!("assets/fonts/{font_name}.ttf");
        output.push_str(&format!("#[allow(dead_code)]\n
pub const {const_name}: &[u8] = include_bytes!({});\n",
            include_assets_path(&asset_path),
        ));
    }

    output.push_str("pub const FONTS: &[(&str, &[u8])] = &[\n");
    for font_name in &font_names {
        let const_name = to_const_name(font_name);
        output.push_str(&format!("(\"{font_name}\", {const_name}),\n"));
    }
    output.push_str("];\n");

    println!("cargo:warning=generated fonts: {:?}", font_names);

    let out_path = Path::new(out_dir).join("fonts_generated.rs");
    fs::write(&out_path, output).expect("failed to write generated fonts");
}
